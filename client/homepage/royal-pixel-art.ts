export type RoyalPixel = { x: number; y: number; shade: number; batch: number };
const key = (x: number, y: number) => `${x},${y}`;

// Pair-specific optical kerning gaps (in grid pixels) after each letter
const OPTICAL_KERNING = [2, 2, 3, 3, 2, 3, 2, 0] as const;

export function buildRoyalLetters() {
  let origin = 10;
  return ROYAL_GLYPHS.map((glyph, index) => {
    const occupied = new Set<string>();
    glyph.rows.forEach((row, y) => [...row].forEach((value, x) => {
      if (value === '1') occupied.add(key(x, y));
    }));
    const pixels: RoyalPixel[] = [], border = new Set<string>(), shadow = new Set<string>();
    occupied.forEach(cell => {
      const [x, y] = cell.split(',').map(Number);
      const top = !occupied.has(key(x, y - 1));
      const bottom = !occupied.has(key(x, y + 1));
      const left = !occupied.has(key(x - 1, y));
      const right = !occupied.has(key(x + 1, y));
      const innerTop = !top && !occupied.has(key(x, y - 2));
      const innerLeft = !left && !occupied.has(key(x - 2, y));
      const grain = (x * 19 + y * 7 + index * 31) % 113;

      // Chiseled V-cut white marble / silver-ivory epigraphic bevel
      let shade = top
        ? 0
        : left
          ? (bottom ? 4 : 0)
          : bottom
            ? 6
            : right
              ? 5
              : innerTop || innerLeft
                ? 1
                : y < 10
                  ? 1
                  : y < 16
                    ? 2
                    : y < 22
                      ? 3
                      : 4;

      const crack = (x === 4 + (index % 2) && y >= 9 && y <= 10) || (x === glyph.rows[0].length - 5 && y === 28);
      if (crack) shade = 7;
      else if ((bottom || grain < 3) && y > 6 && grain < 10) shade = grain % 2 ? 8 : 9;
      else if (grain === 17 && y > 3) shade = 10;

      pixels.push({ x: origin + x, y: 38 + y, shade, batch: (x * 11 + y * 7 + index * 13) % 16 });
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) border.add(key(origin + x + dx, 38 + y + dy));
      for (let depth = 1; depth <= 2; depth++) shadow.add(key(origin + x + depth, 38 + y + depth));
    });
    const result = { letter: glyph.letter, pixels, border: [...border], shadow: [...shadow] };
    origin += glyph.rows[0].length + OPTICAL_KERNING[index];
    return result;
  });
}

export const ROYAL_LETTERS = buildRoyalLetters();
export const ROYAL_PIXELS = ROYAL_LETTERS.flatMap(letter => letter.pixels);
export const pixelPath = (pixels: readonly { x: number; y: number }[]) => pixels.map(({ x, y }) => `M${x} ${y}h1v1h-1z`).join('');
export const cellPath = (cells: readonly string[]) => pixelPath(cells.map(cell => {
  const [x, y] = cell.split(',').map(Number);
  return { x, y };
}));
