export type RoyalPixel={x:number;y:number;shade:number;batch:number};
const key=(x:number,y:number)=>`${x},${y}`;
export function buildRoyalLetters(){
  let origin=8;
  return ROYAL_GLYPHS.map((glyph,index)=>{
    const occupied=new Set<string>();
    glyph.rows.forEach((row,y)=>[...row].forEach((value,x)=>{if(value==='1')occupied.add(key(x,y));}));
    const pixels:RoyalPixel[]=[],border=new Set<string>(),shadow=new Set<string>();
    occupied.forEach(cell=>{
      const [x,y]=cell.split(',').map(Number),top=!occupied.has(key(x,y-1)),bottom=!occupied.has(key(x,y+1)),left=!occupied.has(key(x-1,y));
      const grain=(x*19+y*7+index*31)%113;
      let shade=top?0:left?1:bottom?6:!occupied.has(key(x+1,y))?5:y<10?2:y<15?3:y<18?1:3;
      // Fine authored fracture cadence; patina is limited to chips and shaded edge recesses.
      const crack=(x===5+(index%3)&&y>=8&&y<=11)||(x===glyph.rows[0].length-5&&y===28);
      if(crack)shade=7;
      else if((bottom||grain<3)&&y>5&&grain<12)shade=grain%2?8:9;
      else if(grain===17&&y>3)shade=11;
      pixels.push({x:origin+x,y:38+y,shade,batch:(x*11+y*7+index*13)%16});
      for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++)border.add(key(origin+x+dx,38+y+dy));
      for(let depth=1;depth<=3;depth++)shadow.add(key(origin+x+depth,38+y+depth));
    });
    const result={letter:glyph.letter,pixels,border:[...border],shadow:[...shadow]};
    origin+=glyph.rows[0].length+3;
    return result;
  });
}
export const ROYAL_LETTERS=buildRoyalLetters();
export const ROYAL_PIXELS=ROYAL_LETTERS.flatMap(letter=>letter.pixels);
export const pixelPath=(pixels:readonly {x:number;y:number}[])=>pixels.map(({x,y})=>`M${x} ${y}h1v1h-1z`).join('');
export const cellPath=(cells:readonly string[])=>pixelPath(cells.map(cell=>{const [x,y]=cell.split(',').map(Number);return{x,y};}));
