// Writes a `<name>.d.json.ts` type for every world pack in worlds/. TypeScript then reads each pack as a
// WorldPack instead of inferring a type from megabytes of JSON; with dozens of packs that inference overflows
// the compiler ("Map maximum size exceeded"). Run after adding a world: node scripts/write-world-types.mjs
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const worlds = join(root, "worlds");

function* jsonFiles(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* jsonFiles(path);
    else if (name.endsWith(".json")) yield path;
  }
}

export function worldTypeSource(jsonPath) {
  const types = relative(dirname(jsonPath), join(root, "src", "types.ts")).split("\\").join("/");
  return `// Generated by scripts/write-world-types.mjs: the pack is typed, not inferred.\nimport type { WorldPack } from "${types.startsWith(".") ? types : `./${types}`}";\ndeclare const pack: WorldPack;\nexport default pack;\n`;
}

/** Writes or refreshes every stub; returns how many changed. */
export function writeAll() {
  let written = 0;
  for (const json of jsonFiles(worlds)) {
    const target = json.replace(/\.json$/, ".d.json.ts");
    const source = worldTypeSource(json);
    if (existsSync(target) && readFileSync(target, "utf8") === source) continue;
    writeFileSync(target, source);
    written++;
  }
  return written;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(`World pack types: ${writeAll()} written.`);
